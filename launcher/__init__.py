"""業務ツール統合ランチャー。

このパッケージには**ランチャー自身の機能だけ**を置く。日報・カレンダー・
看板・総合ツールの業務ロジックは、それぞれのリポジトリに残したままにする
(要件定義書 §4「各業務ツールの業務ロジックはランチャーへ移さない」)。

ここが持つのは次の5つだけ:

    app_config     … ランチャー自身の設定とローカル領域
    logging_utils  … ログ初期化
    health         … 相手ツールの `/api/health` を叩く
    tool_registry  … どのツールをどう起動するかの設定 (SQLite)
    ui             … 常駐バーと設定画面 (tkinter)

`ui` 以外は tkinter を読み込まない。画面が無い環境 (試験・診断) でも
起動判定と停止だけは動かせるようにするため。
"""

# ランチャーの版。**出どころはここ1つ。**
#
# `config/launcher.json` ではなくソースに置くのは、「どの版か」の答えを
# 必ず得られるようにするため。設定ファイルは端末ごとに書き換わるし、
# 壊れることもある。壊れたときに版まで分からなくなると、**いちばん
# 版を知りたい場面で答えが出ない**。
#
# アプリID・表示名・ポートは端末ごとに変わりうるので設定に置くが、
# 版はコードと一体のもので、フォルダーごとコピーして配る運用でも
# 必ずソースと一緒に動く。設定から変えられるべきではない
# (変えれば嘘になる)。
__version__ = "1.7.2"
